# A principal diferença entre listas e tuplas é que as tuplas são imutáveis, ou seja, não podem ser alteradas após a sua criação.

#Por ser imutável, geralmente se cria uma tupla com os valores dentro, isso dentro de parenteses, separados por vírgula.

tupla = ("Guilherme", 18, 1.73, 70)

#----  Exibição ----
print(tupla)

for valor in tupla:
    print(valor)